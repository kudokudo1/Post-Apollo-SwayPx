#include <assert.h>
#include <stdbool.h>
#include <stdio.h>
#include <sys/socket.h>
#include <unistd.h>
#include <wayland-server.h>
#include "sway/stage_director_news_request_peer.h"

static void no_authority(struct stage_director_news_request_peer_result r) {
	assert(!r.operator_watch_authenticated);
	assert(!r.can_reserve_lease);
	assert(!r.can_launch);
	assert(!r.can_bind_viewer);
	assert(!r.can_clip);
	assert(!r.can_accept_input);
	assert(!r.can_show_popup);
}
static void denied(struct stage_director_news_request_peer_result r,
		enum stage_director_news_request_peer_state expected) {
	no_authority(r);
	assert(r.state == expected);
	assert(!r.same_native_client_candidate);
}
static struct wl_client *make_client(struct wl_display *display,
		int *client_fd) {
	int pair[2] = {-1, -1};
	assert(socketpair(AF_UNIX, SOCK_STREAM, 0, pair) == 0);
	struct wl_client *client = wl_client_create(display, pair[0]);
	if (!client) {
		close(pair[0]);
		close(pair[1]);
		assert(client != NULL);
	}
	*client_fd = pair[1];
	return client;
}
static struct wl_resource *make_resource(struct wl_client *client, int id) {
	struct wl_resource *resource =
		wl_resource_create(client, &wl_surface_interface, 1, id);
	assert(resource != NULL);
	return resource;
}

int main(void) {
	struct wl_display *display = wl_display_create();
	assert(display != NULL);
	int a_fd = -1, b_fd = -1;
	/* Two real Wayland connections, generated by the same OS process. */
	struct wl_client *a = make_client(display, &a_fd);
	struct wl_client *b = make_client(display, &b_fd);
	assert(a != b);
	/* ID 1 is reserved for the client's wl_display resource. */
	struct wl_resource *role_a = make_resource(a, 101);
	struct wl_resource *surface_a = make_resource(a, 102);
	struct wl_resource *request_a = make_resource(a, 103);
	struct wl_resource *request_b = make_resource(b, 104);
	struct wl_resource *role_b = make_resource(b, 105);

	denied(stage_director_news_request_peer_probe(NULL, surface_a, request_a),
		SD_NEWS_REQUEST_PEER_INVALID_RESOURCES);
	denied(stage_director_news_request_peer_probe(role_a, NULL, request_a),
		SD_NEWS_REQUEST_PEER_INVALID_RESOURCES);
	denied(stage_director_news_request_peer_probe(role_a, surface_a, NULL),
		SD_NEWS_REQUEST_PEER_INVALID_RESOURCES);
	denied(stage_director_news_request_peer_probe(role_a, role_a, request_a),
		SD_NEWS_REQUEST_PEER_INVALID_RESOURCES);
	denied(stage_director_news_request_peer_probe(role_a, surface_a, role_a),
		SD_NEWS_REQUEST_PEER_INVALID_RESOURCES);
	denied(stage_director_news_request_peer_probe(role_a, surface_a, surface_a),
		SD_NEWS_REQUEST_PEER_INVALID_RESOURCES);
	denied(stage_director_news_request_peer_probe(role_a, role_b, request_a),
		SD_NEWS_REQUEST_PEER_HOST_CLIENT_MISMATCH);
	/* Same OS user/process is irrelevant: different wl_client is refused. */
	denied(stage_director_news_request_peer_probe(role_a, surface_a, request_b),
		SD_NEWS_REQUEST_PEER_FOREIGN_CLIENT);

	const struct stage_director_news_request_peer_result match =
		stage_director_news_request_peer_probe(role_a, surface_a, request_a);
	no_authority(match);
	assert(match.state == SD_NEWS_REQUEST_PEER_NATIVE_MATCH_CANDIDATE_ONLY);
	assert(match.same_native_client_candidate);

	/* Never use destroyed resource pointers in a later request handler. */
	wl_client_destroy(a);
	wl_client_destroy(b);
	close(a_fd);
	close(b_fd);
	wl_display_destroy(display);
	puts("SD_NEWS_REQUEST_PEER: real wl_resource/client peer identity "
		"candidate-only, same-process foreign client refused, "
		"all authority denied: PASS");
	return 0;
}
